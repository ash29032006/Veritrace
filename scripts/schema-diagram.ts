/*
 * npm run docs:schema
 *
 * Draws the relational schema straight from the PostgreSQL catalog, so the
 * diagram can never drift from 01_schema.sql: every table with its columns
 * and types, PK and FK markers, and an arrow per foreign key labelled with
 * its ON DELETE action. Writes docs/er/relational-schema.dot; the npm script
 * renders it with Graphviz.
 */
import "./_env";
import { writeFileSync } from "node:fs";
import { closePool, query } from "@/lib/db/postgres";

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

async function main() {
  const columns = await query<{ table_name: string; column_name: string; data_type: string; is_nullable: string }>(`
    SELECT c.table_name, c.column_name,
           CASE WHEN c.data_type = 'character varying' THEN 'varchar(' || c.character_maximum_length || ')'
                WHEN c.data_type = 'numeric' THEN 'numeric(' || c.numeric_precision || ',' || c.numeric_scale || ')'
                WHEN c.data_type = 'character' THEN 'char(' || c.character_maximum_length || ')'
                WHEN c.data_type LIKE 'timestamp%' THEN 'timestamptz'
                ELSE c.data_type END AS data_type,
           c.is_nullable
      FROM information_schema.columns c
      JOIN information_schema.tables t ON t.table_name = c.table_name AND t.table_schema = c.table_schema
     WHERE c.table_schema = 'public' AND t.table_type = 'BASE TABLE'
     ORDER BY c.table_name, c.ordinal_position`);

  const pks = await query<{ table_name: string; column_name: string }>(`
    SELECT tc.table_name, kcu.column_name
      FROM information_schema.table_constraints tc
      JOIN information_schema.key_column_usage kcu ON kcu.constraint_name = tc.constraint_name
     WHERE tc.constraint_type = 'PRIMARY KEY' AND tc.table_schema = 'public'`);

  const fks = await query<{ src: string; src_col: string; dst: string; dst_col: string; on_delete: string; name: string }>(`
    SELECT cl.relname AS src, a.attname AS src_col, cf.relname AS dst, af.attname AS dst_col,
           CASE con.confdeltype WHEN 'r' THEN 'RESTRICT' WHEN 'c' THEN 'CASCADE' WHEN 'n' THEN 'SET NULL'
                                WHEN 'a' THEN 'NO ACTION' ELSE 'SET DEFAULT' END AS on_delete,
           con.conname AS name
      FROM pg_constraint con
      JOIN pg_class cl ON cl.oid = con.conrelid
      JOIN pg_class cf ON cf.oid = con.confrelid
      JOIN pg_attribute a  ON a.attrelid = con.conrelid  AND a.attnum = con.conkey[1]
      JOIN pg_attribute af ON af.attrelid = con.confrelid AND af.attnum = con.confkey[1]
     WHERE con.contype = 'f'
     ORDER BY cl.relname, a.attname`);

  const isPk = new Set(pks.map((p) => `${p.table_name}.${p.column_name}`));
  const isFk = new Set(fks.map((f) => `${f.src}.${f.src_col}`));
  const tables = [...new Set(columns.map((c) => c.table_name))];

  const out: string[] = [];
  out.push("// GENERATED by scripts/schema-diagram.ts from the live catalog. Do not edit.");
  out.push("digraph relational_schema {");
  out.push('  graph [rankdir=LR, nodesep=0.5, ranksep=1.1, fontname="Helvetica", bgcolor="white", pad=0.4,');
  out.push('         label=<<B>VERITRACE</B>  relational schema (PostgreSQL)<BR/><FONT POINT-SIZE="11" COLOR="#6e6a88">PK primary key · FK foreign key · arrow label = ON DELETE action</FONT>>, labelloc=t, fontsize=20];');
  out.push('  node [shape=plain, fontname="Helvetica"];');
  out.push('  edge [color="#7c6fb0", fontname="Helvetica", fontsize=10, fontcolor="#6d28d9", arrowsize=0.7];');

  for (const t of tables) {
    const rows = columns
      .filter((c) => c.table_name === t)
      .map((c) => {
        const key = `${t}.${c.column_name}`;
        const tag = [isPk.has(key) ? "PK" : "", isFk.has(key) ? "FK" : ""].filter(Boolean).join(" ");
        const name = isPk.has(key) ? `<B>${esc(c.column_name)}</B>` : esc(c.column_name);
        const nullable = c.is_nullable === "YES" ? "" : " not null";
        return `<TR><TD ALIGN="LEFT" PORT="${c.column_name}">${tag ? `<FONT COLOR="#7c3aed">${tag}</FONT>` : " "}</TD><TD ALIGN="LEFT">${name}</TD><TD ALIGN="LEFT"><FONT COLOR="#6e6a88">${esc(c.data_type)}${nullable}</FONT></TD></TR>`;
      })
      .join("");
    out.push(
      `  ${t} [label=<<TABLE BORDER="1" COLOR="#c9bff0" CELLBORDER="0" CELLSPACING="0" CELLPADDING="4" BGCOLOR="white">` +
        `<TR><TD COLSPAN="3" BGCOLOR="#ede7fb" ALIGN="LEFT"><B>${t}</B></TD></TR>${rows}</TABLE>>];`,
    );
  }
  for (const f of fks) {
    const style = f.on_delete === "CASCADE" ? ', style="bold"' : f.on_delete === "SET NULL" ? ', style="dashed"' : "";
    out.push(`  ${f.src}:${f.src_col} -> ${f.dst}:${f.dst_col} [label="${f.on_delete}"${style}];`);
  }
  out.push("}");
  writeFileSync("docs/er/relational-schema.dot", out.join("\n") + "\n");
  console.log(`wrote docs/er/relational-schema.dot: ${tables.length} tables, ${fks.length} foreign keys`);
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(closePool);

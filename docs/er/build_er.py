"""Generate the VERITRACE Chen-notation ER diagram.

Graphviz places free-floating attribute ovals poorly, so this script pins
every node: entities and relationships at hand-picked coordinates, each
entity's attributes on one or more arcs that face away from its
relationships.

    python3 docs/er/build_er.py      # writes er-diagram.dot next to this file
    npm run docs:er                  # also renders .svg and .png
"""

from math import cos, radians, sin
from pathlib import Path

ENTITY_FILL = "#ede7fb"
ENTITY_LINE = "#4c3a99"
REL_LINE = "#7c3aed"
ATTR_LINE = "#948fb8"
EDGE = "#4c3a99"
ATTR_EDGE = "#b9b3d6"
CARD = "#7c3aed"

# name -> (x, y) in inches
ENTITIES = {
    "APP_USER": (-12.0, 0.0),
    "APP_SESSION": (-17.0, 5.0),
    "BATCH": (0.0, 0.0),
    "OUTLET": (0.0, -10.5),
    "SHIPMENT": (-7.0, -8.0),
    "RECALL": (-6.5, 6.5),
    "COMPLAINT": (9.5, -7.5),
    "AUDIT_LOG": (-14.0, -8.5),
}

RELATIONSHIPS = {
    "COMPOSED_OF": (6.5, 0.0),
    "CONTAINS": (-4.0, -4.2),
    "STOCKS": (0.0, -5.4),
    "SENT_TO": (-3.6, -10.6),
    "TARGETS": (-1.9, 5.0),
    "AFFECTS": (-3.9, 2.6),
    "MATCHED_TO": (5.2, -4.4),
    "REPORTED_AT": (5.2, -10.6),
    "INITIATES": (-10.0, 4.6),
    "CLOSES": (-8.0, 2.4),
    "DISPATCHES": (-9.8, -4.4),
    "PERFORMS": (-13.4, -4.4),
    "HAS_SESSION": (-15.0, 2.4),
}

# entity -> list of arcs (attributes, start deg, end deg, radius).
# A lone arc staggers alternate ovals outward so neighbours never touch.
# "*name" = key (underlined), "~name" = derived (dashed)
ENTITY_ATTRS = {
    "APP_USER": [(["*user_id", "username", "password_hash", "role", "created_at"], 150, 235, 3.2)],
    "APP_SESSION": [(["*token_hash", "created_at", "expires_at"], 70, 175, 2.4)],
    "BATCH": [
        (["*batch_id", "batch_code", "product_name", "description", "manufacture_date"], 16, 96, 4.3),
        # the rest sit in the two free gaps: COMPOSED_OF / MATCHED_TO and MATCHED_TO / STOCKS
        (["quantity_produced"], -22, -22, 3.4),
        (["status"], -62, -62, 2.6),
        (["~quantity_available"], -71, -71, 3.9),
    ],
    "OUTLET": [(["*outlet_id", "outlet_name", "city", "contact_email"], 205, 335, 2.2)],
    "SHIPMENT": [(["*shipment_id", "shipment_date"], 195, 255, 2.4)],
    "RECALL": [(["*recall_id", "reason", "initiated_at", "recall_status", "closed_at"], 55, 165, 3.0)],
    "COMPLAINT": [(["*complaint_id", "complaint_text", "received_at"], -55, 55, 2.7)],
    "AUDIT_LOG": [(["*log_id", "action", "entity_name", "entity_id", "performed_at", "details"],
                   185, 335, 3.0)],
}

# relationship -> [(attribute, dx, dy)]
REL_ATTRS = {
    "COMPOSED_OF": [("quantity_used", 2.6, 0.0)],
    "CONTAINS": [("quantity", -2.4, 0.8)],
    "STOCKS": [("quantity_on_hand", 2.9, 0.5), ("stock_status", 2.6, -0.6)],
    "AFFECTS": [("hop_depth", -2.3, -0.7)],
    "MATCHED_TO": [("similarity_score", 2.6, 0.9)],
}

# (entity, relationship, cardinality, total participation of the entity side)
LINKS = [
    ("SHIPMENT", "CONTAINS", "M", True), ("BATCH", "CONTAINS", "N", False),
    ("SHIPMENT", "SENT_TO", "N", True), ("OUTLET", "SENT_TO", "1", False),
    ("OUTLET", "STOCKS", "M", False), ("BATCH", "STOCKS", "N", False),
    ("RECALL", "TARGETS", "N", True), ("BATCH", "TARGETS", "1", False),
    ("RECALL", "AFFECTS", "M", True), ("BATCH", "AFFECTS", "N", False),
    ("COMPLAINT", "MATCHED_TO", "N", False), ("BATCH", "MATCHED_TO", "1", False),
    ("COMPLAINT", "REPORTED_AT", "N", False), ("OUTLET", "REPORTED_AT", "1", False),
    ("APP_USER", "INITIATES", "1", False), ("RECALL", "INITIATES", "N", True),
    ("APP_USER", "CLOSES", "1", False), ("RECALL", "CLOSES", "N", False),
    ("APP_USER", "DISPATCHES", "1", False), ("SHIPMENT", "DISPATCHES", "N", True),
    ("APP_USER", "PERFORMS", "1", False), ("AUDIT_LOG", "PERFORMS", "N", False),
    ("APP_USER", "HAS_SESSION", "1", False), ("APP_SESSION", "HAS_SESSION", "N", True),
]


def attr_label(raw: str) -> tuple[str, str]:
    if raw.startswith("*"):
        return f"<<U>{raw[1:]}</U>>", "filled"
    if raw.startswith("~"):
        return f'"{raw[1:]}"', "dashed,filled"
    return f'"{raw}"', "filled"


def arc_positions(arcs: list[tuple[list[str], float, float, float]]):
    stagger = len(arcs) == 1
    for attrs, start, end, radius in arcs:
        n = len(attrs)
        for i, raw in enumerate(attrs):
            deg = start + (end - start) * (i / (n - 1) if n > 1 else 0.5)
            r = radius + (0.75 if stagger and i % 2 else 0.0)
            yield raw, radians(deg), r


def build() -> str:
    out: list[str] = []
    w = out.append
    w("// VERITRACE ER diagram, Chen notation. GENERATED by docs/er/build_er.py; edit that, not this.")
    w("graph veritrace_er {")
    w('  layout=neato; splines=true; outputorder=edgesfirst; bgcolor="white"; pad=0.5;')
    w('  fontname="Helvetica"; labelloc=t; fontsize=22;')
    w('  label=<<B>VERITRACE</B>  ER diagram (Chen notation)<BR/>'
      '<FONT POINT-SIZE="12" COLOR="#6e6a88">rectangle entity · diamond relationship · '
      'ellipse attribute · <U>underline</U> key · dashed derived · double line total participation · '
      'foreign keys appear as relationships</FONT>>;')
    w(f'  edge [color="{EDGE}", penwidth=1.25, fontname="Helvetica-Bold", fontsize=13, fontcolor="{CARD}"];')

    w(f'  node [shape=box, style=filled, fillcolor="{ENTITY_FILL}", color="{ENTITY_LINE}", '
      'penwidth=1.6, fontname="Helvetica-Bold", fontsize=15, width=1.9, height=0.6];')
    for name, (x, y) in ENTITIES.items():
        w(f'  {name} [label="{name}", pos="{x},{y}!"];')

    w(f'  node [shape=diamond, style=filled, fillcolor="#ffffff", color="{REL_LINE}", '
      'penwidth=1.5, fontname="Helvetica-Bold", fontsize=11, width=2.1, height=1.0];')
    for name, (x, y) in RELATIONSHIPS.items():
        w(f'  {name} [label="{name}", pos="{x},{y}!"];')

    w(f'  node [shape=ellipse, style=filled, fillcolor="#ffffff", color="{ATTR_LINE}", '
      'penwidth=1.1, fontname="Helvetica", fontsize=11, width=0.4, height=0.36, margin="0.07,0.02"];')
    attr_edges: list[str] = []
    for ent, arcs in ENTITY_ATTRS.items():
        ex, ey = ENTITIES[ent]
        for raw, angle, r in arc_positions(arcs):
            label, style = attr_label(raw)
            aid = f"{ent}__{raw.strip('*~')}"
            w(f'  {aid} [label={label}, style="{style}", '
              f'pos="{ex + r * cos(angle):.2f},{ey + r * sin(angle):.2f}!"];')
            attr_edges.append(f"  {ent} -- {aid};")
    for rel, items in REL_ATTRS.items():
        rx, ry = RELATIONSHIPS[rel]
        for name, dx, dy in items:
            aid = f"{rel}__{name}"
            w(f'  {aid} [label="{name}", pos="{rx + dx:.2f},{ry + dy:.2f}!"];')
            attr_edges.append(f"  {rel} -- {aid};")

    w(f'  edge [color="{ATTR_EDGE}", penwidth=1.0];')
    out.extend(attr_edges)

    w(f'  edge [color="{EDGE}", penwidth=1.3];')
    # The recursive M:N on BATCH: two role-labelled lines, one from each side.
    w('  BATCH:ne -- COMPOSED_OF:n [label="M  parent (input)  "];')
    w('  BATCH:se -- COMPOSED_OF:s [label="N  child (consumer)  "];')
    for ent, rel, card, total in LINKS:
        colour = f',color="{EDGE}:invis:{EDGE}"' if total else ""
        w(f'  {ent} -- {rel} [label="{card}"{colour}];')
    w("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    target = Path(__file__).with_name("er-diagram.dot")
    target.write_text(build())
    print(f"wrote {target}")
